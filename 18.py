#размеры отверстия
a,b=map(int,input().split('x'))
#размеры кирпича
c,d,e=map(int,input().split('x'))
#для получения меньшей и большей величины сортируем
hole=sorted([a,b])
#для получения меньшей,средней и большей величины сортируем
brick=sorted([c,d,e])
#крипич должен пролезть, если его стороны не больше сторон дырки
if brick[0]<=hole[0] and brick[1]<=hole[1]:
    print("да")
else:
    print("нет")