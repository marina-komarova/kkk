xc=int(input()) #координата центра
yc=int(input()) #координата центра
r=int(input()) #радиус
x=int(input()) #координата проверяемой точки
y=int(input()) #координата проверяемой точки

# квадрат расстояния от точки до центра
d=(x-xc)**2+(y-yc)**2
if d<r**2:
    print("точка внутри окружности")
elif d==r**2:
    print("точка лежит на окружности")
else:
    print("точка за окружностью")
